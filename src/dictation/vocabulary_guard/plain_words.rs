/// Whether a word, as compared, means something on its own.
pub(super) fn is_content(norm: &str) -> bool {
    norm.chars().filter(|c| c.is_alphabetic()).count() >= MIN_CONTENT_CHARS
        && PLAIN.binary_search(&norm).is_err()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_list_is_sorted_so_the_search_finds_every_word() {
        assert!(PLAIN.windows(2).all(|pair| pair[0] < pair[1]), "unsorted");
        assert!(!is_content("короче") && !is_content("the") && !is_content("ну"));
        assert!(is_content("barn") && is_content("сарай"));
    }
}
